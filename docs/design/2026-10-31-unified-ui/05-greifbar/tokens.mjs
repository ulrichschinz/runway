#!/usr/bin/env node
// Greifbar: the token generator (the proposal's tools/tokens.mjs, no dependencies).
//   node tokens.mjs            writes tokens.css next to this file and Tokens.kt (sample for runway-android)
// tokens.json is the only source. CSS keeps color-mix() so the browser resolves it; Kotlin gets the
// same mixes resolved to sRGB hex (color-mix in srgb = per-channel lerp of the encoded values).
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const dir = path.dirname(fileURLToPath(import.meta.url))
const T = JSON.parse(fs.readFileSync(path.join(dir, 'tokens.json'), 'utf8'))
const kebab = (s) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)
const pascal = (s) => s[0].toUpperCase() + s.slice(1)

// ---------- CSS ----------
const cssValue = (v) => {
  if (v.ref) return `var(--ar-${kebab(v.ref)})`
  const [a, p, b] = v.mix
  return `color-mix(in srgb, var(--ar-${kebab(a)}) ${p}%, ${b === 'transparent' ? 'transparent' : `var(--ar-${kebab(b)})`})`
}
const block = (set, indent) => Object.entries(set).filter(([k]) => !k.startsWith('$'))
  .map(([k, v]) => `${indent}--rw-${kebab(k)}: ${cssValue(v)};`).join('\n')
const css = `/* GENERATED by tokens.mjs from tokens.json. Do not edit. */
:root {
${block(T.color.light, '  ')}
  color-scheme: light;
}
@media (prefers-color-scheme: dark) {
  :root {
${block(T.color.dark, '    ')}
    color-scheme: dark;
  }
}
`
fs.writeFileSync(path.join(dir, 'tokens.css'), css)

// ---------- Kotlin ----------
const hex = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16))
function resolve(v) {
  if (v.ref) return [...hex(T.brand[v.ref]), 255]
  const [a, p, b] = v.mix
  const A = hex(T.brand[a]), k = p / 100
  if (b === 'transparent') return [...A, Math.round(255 * k)]
  const B = hex(T.brand[b])
  return [...A.map((x, i) => Math.round(x * k + B[i] * (1 - k))), 255]
}
const argb = ([r, g, b, a]) => `0x${[a, r, g, b].map((x) => x.toString(16).padStart(2, '0')).join('').toUpperCase()}`
const kColors = (set, suffix) => Object.entries(set).filter(([k]) => !k.startsWith('$'))
  .map(([k, v]) => `    val ${pascal(k)}${suffix} = Color(${argb(resolve(v))}) // ${v.ref ? v.ref : v.mix.join(' ')}`).join('\n')
const springs = Object.entries(T.compose).filter(([k]) => !k.startsWith('$'))
  .map(([k, v]) => `    fun <T> ${k}() = spring<T>(dampingRatio = ${v.dampingRatio}f, stiffness = ${v.stiffness}f)`).join('\n')
const kt = `// GENERATED by tokens.mjs from tokens.json. Do not edit.
package com.agenticreach.runway.ui.theme

import androidx.compose.animation.core.spring
import androidx.compose.ui.graphics.Color

object RwLight {
${kColors(T.color.light, '')}
}

object RwDark {
${kColors(T.color.dark, '')}
}

object RwGl {
${kColors(T.gl.light, 'Light')}
${kColors(T.gl.dark, 'Dark')}
}

object RwSprings {
${springs}
}
`
fs.writeFileSync(path.join(dir, 'Tokens.kt'), kt)
console.log('wrote tokens.css and Tokens.kt')
