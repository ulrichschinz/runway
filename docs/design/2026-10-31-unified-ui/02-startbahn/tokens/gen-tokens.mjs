#!/usr/bin/env node
// Startbahn token generator: tokens.json -> tokens.css (web) + RunwayTokens.kt (Compose).
// Run from this folder: node gen-tokens.mjs. The outputs are committed, so viewing the
// prototype needs no build step. In the real repos this script would live in one place
// (e.g. runway/design-tokens/) and both builds would call it.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const T = JSON.parse(fs.readFileSync(path.join(here, 'tokens.json'), 'utf8'))
const cssVar = { coral: '--ar-coral', plum: '--ar-plum', yellow: '--ar-yellow', ink: '--ar-ink', bg: '--ar-bg', bgAlt: '--ar-bg-alt', bgCool: '--ar-bg-cool', paper: '--ar-paper' }

const hex2rgb = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16))
// CSS: keep the derivation visible (color-mix on brand variables).
function toCss(v) {
  if (typeof v === 'string') return `var(${cssVar[v]})`
  const [op, a, pct, b] = v
  if (op === 'mix') return `color-mix(in srgb, var(${cssVar[a]}) ${pct}%, var(${cssVar[b]}))`
  if (op === 'alpha') return `color-mix(in srgb, var(${cssVar[a]}) ${pct}%, transparent)`
  throw new Error(`unknown op ${op}`)
}
// Kotlin: resolve to ARGB (same sRGB mix as color-mix(in srgb …)).
function toArgb(v) {
  if (typeof v === 'string') return [255, ...hex2rgb(T.brand[v])]
  const [op, a, pct, b] = v
  const ca = hex2rgb(T.brand[a])
  if (op === 'alpha') return [Math.round(255 * pct / 100), ...ca]
  const cb = hex2rgb(T.brand[b])
  return [255, ...ca.map((x, i) => Math.round(x * pct / 100 + cb[i] * (1 - pct / 100)))]
}
const camel = (s) => s.replace(/-([a-z])/g, (_, c) => c.toUpperCase())
const hx = (n) => n.toString(16).padStart(2, '0').toUpperCase()

let css = `/* Generated by tokens/gen-tokens.mjs from tokens.json. Do not edit by hand. */\n:root {\n`
for (const [k, v] of Object.entries(T.color)) css += `  --rw-${k}: ${toCss(v.light)};\n`
for (const [k, v] of Object.entries(T.radius)) css += `  --rw-radius-${k}: ${v}px;\n`
for (const [k, v] of Object.entries(T.space)) css += `  --rw-space-${k}: ${v}px;\n`
for (const [k, v] of Object.entries(T.type)) {
  const fam = { sans: 'var(--ar-font-sans)', mono: 'var(--ar-font-mono)', serif: 'var(--ar-font-serif)' }[v.family]
  css += `  --rw-type-${k}: ${v.style === 'italic' ? 'italic ' : ''}${v.weight} ${v.size}px/${v.line}px ${fam};\n`
  css += `  --rw-tracking-${k}: ${v.tracking}em;\n`
}
for (const [k, v] of Object.entries(T.motion)) {
  css += Array.isArray(v) ? `  --rw-${k}: cubic-bezier(${v.join(', ')});\n` : `  --rw-dur-${k}: ${v}ms;\n`
}
css += `}\n`
const dark = Object.entries(T.color).map(([k, v]) => `  --rw-${k}: ${toCss(v.dark)};`).join('\n')
css += `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) {\n${dark.replace(/^/gm, '  ')}\n  }\n}\n`
css += `:root[data-theme="dark"] {\n${dark}\n}\n`
fs.writeFileSync(path.join(here, 'tokens.css'), css)

let kt = `// Generated by tokens/gen-tokens.mjs from tokens.json. Do not edit by hand.\npackage com.agenticreach.runway.ui.theme\n\n`
kt += `import androidx.compose.animation.core.CubicBezierEasing\nimport androidx.compose.ui.graphics.Color\nimport androidx.compose.ui.unit.dp\n\n`
kt += `data class RunwayColors(\n${Object.keys(T.color).map((k) => `    val ${camel(k)}: Color,`).join('\n')}\n)\n\n`
for (const mode of ['light', 'dark']) {
  kt += `val ${mode}RunwayColors = RunwayColors(\n`
  kt += Object.entries(T.color).map(([k, v]) => {
    const [a, r, g, b] = toArgb(v[mode])
    return `    ${camel(k)} = Color(0x${hx(a)}${hx(r)}${hx(g)}${hx(b)}),`
  }).join('\n')
  kt += `\n)\n\n`
}
kt += `object RunwayShape {\n${Object.entries(T.radius).map(([k, v]) => `    val ${k} = ${v}.dp`).join('\n')}\n}\n\n`
kt += `object RunwayMotion {\n`
for (const [k, v] of Object.entries(T.motion)) {
  kt += Array.isArray(v) ? `    val ${camel(k)} = CubicBezierEasing(${v.map((n) => `${n}f`).join(', ')})\n` : `    const val ${camel(k)}Ms = ${v}\n`
}
kt += `}\n`
fs.writeFileSync(path.join(here, 'RunwayTokens.kt'), kt)
console.log('wrote tokens.css and RunwayTokens.kt')
