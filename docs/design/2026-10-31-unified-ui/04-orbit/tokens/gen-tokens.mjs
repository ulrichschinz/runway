#!/usr/bin/env node
// One token source, two outputs: CSS variables for the Vue app and a Compose theme for Android.
// Usage (from 04-orbit/): node tokens/gen-tokens.mjs
// Colour expressions in tokens.json:
//   "coral"                -> a brand colour
//   "mix(plum 45%, bg)"    -> color-mix(in srgb, plum 45%, bg)
//   "alpha(ink 10%)"       -> color-mix(in srgb, ink 10%, transparent)
// CSS keeps the color-mix() expression (the brand rule: derive, never invent a hex value).
// Kotlin gets the resolved ARGB value, because Compose has no color-mix.

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const dir = path.dirname(fileURLToPath(import.meta.url))
const T = JSON.parse(fs.readFileSync(path.join(dir, 'tokens.json'), 'utf8'))

const kebab = (s) => s.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase())
const brandVar = (name) => `var(--ar-${kebab(name)})`
const hex = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16))

function parse(expr) {
  let m
  if ((m = /^mix\((\w+) (\d+)%, (\w+)\)$/.exec(expr))) return { kind: 'mix', a: m[1], p: +m[2] / 100, b: m[3] }
  if ((m = /^alpha\((\w+) (\d+)%\)$/.exec(expr))) return { kind: 'alpha', a: m[1], p: +m[2] / 100 }
  if (T.brand[expr]) return { kind: 'brand', a: expr }
  throw new Error(`unknown colour expression: ${expr}`)
}

function css(expr) {
  const e = parse(expr)
  if (e.kind === 'brand') return brandVar(e.a)
  if (e.kind === 'alpha') return `color-mix(in srgb, ${brandVar(e.a)} ${Math.round(e.p * 100)}%, transparent)`
  return `color-mix(in srgb, ${brandVar(e.a)} ${Math.round(e.p * 100)}%, ${brandVar(e.b)})`
}

function argb(expr) {
  const e = parse(expr)
  const A = hex(T.brand[e.a])
  let rgb = A, alpha = 1
  if (e.kind === 'mix') {
    const B = hex(T.brand[e.b])
    rgb = A.map((v, i) => Math.round(v * e.p + B[i] * (1 - e.p)))
  } else if (e.kind === 'alpha') alpha = e.p
  const h = (n) => n.toString(16).padStart(2, '0').toUpperCase()
  return `0x${h(Math.round(alpha * 255))}${rgb.map(h).join('')}`
}

// ---- CSS ----
const block = (mode) => Object.entries(T.color[mode]).map(([k, v]) => `  --o-${kebab(k)}: ${css(v)};`).join('\n')
const fam = { sans: 'var(--ar-font-sans)', serif: 'var(--ar-font-serif)', mono: 'var(--ar-font-mono)' }
const typeCss = Object.entries(T.type).map(([k, t]) =>
  `  --o-type-${kebab(k)}: ${t.italic ? 'italic ' : ''}${t.weight} ${t.size}px/${t.line}px ${fam[t.family]};\n` +
  `  --o-track-${kebab(k)}: ${t.tracking}em;`).join('\n')
const shapeCss = Object.entries(T.shape).map(([k, v]) => `  --o-radius-${k}: ${v}px;`).join('\n')
const motionCss = Object.entries(T.motion).map(([k, v]) => `  --o-${kebab(k)}: ${typeof v === 'number' ? v + 'ms' : v};`).join('\n')

const cssOut = `/* GENERATED by tokens/gen-tokens.mjs from tokens/tokens.json. Do not edit by hand. */
:root {
${block('light')}
${typeCss}
${shapeCss}
${motionCss}
  color-scheme: light;
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${block('dark').replace(/^/gm, '  ')}
    color-scheme: dark;
  }
}
:root[data-theme="dark"] {
${block('dark')}
  color-scheme: dark;
}
`
fs.writeFileSync(path.join(dir, 'orbit-tokens.css'), cssOut)

// ---- Kotlin ----
const kColors = (mode) => Object.entries(T.color[mode]).map(([k, v]) => `    ${k} = Color(${argb(v)}),  // ${v}`).join('\n')
const kFam = { sans: 'SpaceGrotesk', serif: 'Fraunces', mono: 'JetBrainsMono' }
const kType = Object.entries(T.type).map(([k, t]) =>
  `    val ${k} = TextStyle(fontFamily = ${kFam[t.family]}, fontWeight = FontWeight(${t.weight}), ` +
  `fontSize = ${t.size + 1}.sp, lineHeight = ${t.line + 3}.sp, letterSpacing = ${t.tracking}.em` +
  `${t.italic ? ', fontStyle = FontStyle.Italic' : ''})`).join('\n')
const kMotion = Object.entries(T.motion).filter(([, v]) => typeof v === 'number').map(([k, v]) => `    const val ${k} = ${v}`).join('\n')
const names = Object.keys(T.color.light)

const kt = `// GENERATED by tokens/gen-tokens.mjs from tokens/tokens.json. Do not edit by hand.
// Target: runway-android app/src/main/java/com/agenticreach/runway/ui/theme/OrbitTheme.kt
package com.agenticreach.runway.ui.theme

import androidx.compose.runtime.Immutable
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.text.TextStyle
import androidx.compose.ui.text.font.FontStyle
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.em
import androidx.compose.ui.unit.sp

@Immutable
data class OrbitColors(
${names.map((n) => `    val ${n}: Color,`).join('\n')}
)

val OrbitLight = OrbitColors(
${kColors('light')}
)

val OrbitDark = OrbitColors(
${kColors('dark')}
)

// Android sizes are one step larger than web (sp, read at arm's length). Fonts come from res/font.
object OrbitType {
${kType}
}

object OrbitMotion {
${kMotion}
    // easing: CubicBezierEasing(0.2f, 0.8f, 0.2f, 1f) standard, CubicBezierEasing(0.65f, 0f, 0.35f, 1f) camera
}

object OrbitGeometry {
    const val hub = ${T.orbit.hub}f
    const val rimIn = ${T.orbit.rimIn}f
    const val rimOut = ${T.orbit.rimOut}f
    val rings = floatArrayOf(${T.orbit.rings.map((r) => r + 'f').join(', ')})
    const val wait = ${T.orbit.wait}f
    const val tray = ${T.orbit.tray}f
    const val bead = ${T.orbit.bead}f
    const val hubRing = ${T.orbit.hubRing}f      // beads without a context sit on the hub
    const val groove = ${T.orbit.groove}f        // gap between sectors, drawn with a 1 dp line
    const val minSector = ${T.orbit.minSector}f  // radians; sectors are weighted by count above this
    const val cellMax = ${T.orbit.cellMax}       // beads per ring and sector before a "+N" marker
    const val trayMax = ${T.orbit.trayMax}       // inbox beads in the tray before a "+N" marker
    const val trayArc = ${T.orbit.trayArc}f      // half-width of the tray in radians
}
`
fs.mkdirSync(path.join(dir, 'android'), { recursive: true })
fs.writeFileSync(path.join(dir, 'android', 'OrbitTheme.kt'), kt)
console.log('wrote tokens/orbit-tokens.css and tokens/android/OrbitTheme.kt')
