# --- file helpers -------------------------------------------------------------


def write(path: Path, body: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(body, encoding="utf-8")


def edit(path: Path, transform) -> None:
    text = path.read_text(encoding="utf-8")
    path.write_text(transform(text), encoding="utf-8")


def insert_before_marker(text: str, marker: str, block: str) -> str:
    if marker not in text:
        raise Tooling(f"architecture.toml has lost its `{marker}` marker")
    return text.replace(marker, block + marker, 1)


def grant_edge(text: str, source_unit: str, target_unit: str) -> str:
    """Add one unit id to an existing allowed_edges entry's `to` list."""
    pattern = re.compile(
        r'(\[\[allowed_edges\]\]\nfrom = "' + re.escape(source_unit) + r'"\nto = \[)([^\]]*)(\])'
    )
    match = pattern.search(text)
    if not match:
        raise Tooling(f"architecture.toml has no allowed_edges entry for `{source_unit}`")
    if f'"{target_unit}"' in match.group(2):
        return text
    return text[: match.end(2)] + f', "{target_unit}"' + text[match.end(2) :]


def declared_units() -> set[str]:
    with open(ARCHITECTURE, "rb") as fh:
        return {unit["id"] for unit in tomllib.load(fh)["units"]}


# --- the two kinds ------------------------------------------------------------


def backend_feature(name: str) -> tuple[list[Path], list[Path]]:
    created = {
        ROOT / "backend" / "app" / f"{name}_models.py": BACKEND_MODELS,
        ROOT / "backend" / "app" / "services" / f"{name}_service.py": BACKEND_SERVICE,
        ROOT / "backend" / "app" / "routers" / f"{name}.py": BACKEND_ROUTER,
        ROOT / "backend" / "tests" / "unit" / f"test_{name}.py": BACKEND_UNIT_TEST,
        ROOT / "backend" / "tests" / "container" / f"test_{name}.py": BACKEND_CONTAINER_TEST,
    }
    refuse_if_present(created, f"be/feature/{name}")

    for path, template in created.items():
        write(path, render(template, name))

    edit(ARCHITECTURE, lambda t: architecture_for_backend(t, name))
    edit(ROUTE_GUARDS, lambda t: declare_guard(t, f"GET /{name}"))
    edit(MAIN, lambda t: mount_router(t, name))
    edit(CONTRACT, lambda t: bump_surface_counts(t, 1))

    return list(created), [ARCHITECTURE, ROUTE_GUARDS, MAIN, CONTRACT]


def architecture_for_backend(text: str, name: str) -> str:
    text = insert_before_marker(text, UNIT_MARKER, render(BACKEND_UNIT_BLOCK, name))
    text = insert_before_marker(text, EDGE_MARKER, render(BACKEND_EDGE_BLOCK, name))
    text = grant_edge(text, "be/app", f"be/feature/{name}")
    return grant_edge(text, "tests", f"be/feature/{name}")


def frontend_feature(name: str) -> tuple[list[Path], list[Path]]:
    views = ROOT / "frontend" / "src" / "views"
    created = {
        views / f"_use{pascal(name)}.js": FRONTEND_LOGIC,
        views / f"{pascal(name)}View.vue": FRONTEND_VIEW,
        ROOT / "frontend" / "tests" / f"{name}.test.js": FRONTEND_TEST,
    }
    refuse_if_present(created, f"fe/{name}")

    for path, template in created.items():
        write(path, render(template, name))

    edit(ARCHITECTURE, lambda t: architecture_for_frontend(t, name))
    edit(SPA_ROUTER, lambda t: mount_view(t, name))

    return list(created), [ARCHITECTURE, SPA_ROUTER]


def architecture_for_frontend(text: str, name: str) -> str:
    text = insert_before_marker(text, UNIT_MARKER, render(FRONTEND_UNIT_BLOCK, name))
    text = insert_before_marker(text, EDGE_MARKER, render(FRONTEND_EDGE_BLOCK, name))
    text = grant_edge(text, "fe/app", f"fe/{name}")
    return grant_edge(text, "tests", f"fe/{name}")


def refuse_if_present(created: dict[Path, str], unit_id: str) -> None:
    """Never overwrite. A scaffold that clobbers is worse than one that refuses, because the
    thing it clobbers is somebody's work and the generator looks like it succeeded."""
    if unit_id in declared_units():
        raise NeedsInput(
            f"architecture.toml already declares `{unit_id}`. "
            "Pick another NAME, or remove the existing unit first."
        )
    for path in created:
        if path.exists():
            raise NeedsInput(
                f"{path.relative_to(ROOT)} already exists. "
                "Pick another NAME, or remove the existing files first."
            )


# --- edits to hand-written files ----------------------------------------------


def declare_guard(text: str, route: str) -> str:
    """Insert a guard declaration, keeping rules/route-guards.toml in its sorted order."""
    block = f'[[routes]]\nroute = "{route}"\nguard = "user"\n\n'
    method, path = route.split(" ", 1)
    for match in re.finditer(r'^\[\[routes\]\]\nroute = "(\S+) (\S+)"$', text, re.MULTILINE):
        if (match.group(2), match.group(1)) > (path, method):
            return text[: match.start()] + block + text[match.start() :]
    return text.rstrip("\n") + "\n\n" + block.rstrip("\n") + "\n"


def mount_router(text: str, name: str) -> str:
    """Import the router in backend/app/main.py and include it."""
    imports = re.search(r"^from app\.routers import (.+)$", text, re.MULTILINE)
    if not imports:
        raise Tooling("backend/app/main.py does not import app.routers the expected way")
    modules = sorted([*(m.strip() for m in imports.group(1).split(",")), name])
    text = text[: imports.start()] + f"from app.routers import {', '.join(modules)}" + text[imports.end() :]

    includes = list(re.finditer(r"^app\.include_router\(\w+\.router\)$", text, re.MULTILINE))
    if not includes:
        raise Tooling("backend/app/main.py includes no routers")
    last = includes[-1]
    return text[: last.end()] + f"\napp.include_router({name}.router)" + text[last.end() :]


def mount_view(text: str, name: str) -> str:
    """Import the view in frontend/src/router/index.js and give it a route."""
    view = f"{pascal(name)}View"
    imports = list(re.finditer(r"^import \w+ from '\.\./views/\w+\.vue'$", text, re.MULTILINE))
    if not imports:
        raise Tooling("frontend/src/router/index.js imports no views")
    last = imports[-1]
    text = text[: last.end()] + f"\nimport {view} from '../views/{view}.vue'" + text[last.end() :]

    start = text.find("const routes = [")
    end = text.find("\n]", start)
    if start < 0 or end < 0:
        raise Tooling("frontend/src/router/index.js has no routes array")
    return text[:end] + f"\n  {{ path: '/{name}', component: {view} }}," + text[end:]


def bump_surface_counts(text: str, added: int) -> str:
    """AGENTS.md states how many REST routes and MCP tools exist, and RULE-DOC-001 checks
    both against the index. A new route moves both numbers."""
    for pattern in (r"REST API \((\d+) routes\)", r"MCP tools \((\d+)\)"):
        match = re.search(pattern, text)
        if not match:
            raise Tooling(f"AGENTS.md no longer states a count matching /{pattern}/")
        new = str(int(match.group(1)) + added)
        text = text[: match.start(1)] + new + text[match.end(1) :]
    return text


# --- finishing the job --------------------------------------------------------


def run(*command: str, why: str) -> None:
    result = subprocess.run(command, cwd=ROOT, capture_output=True, text=True)
    if result.returncode != 0:
        raise Tooling(f"{why} failed:\n{result.stdout}{result.stderr}")


def stage(paths: list[Path]) -> None:
    """`git add` what was generated.

    Not a convenience. The index reads `git ls-files`, so an untracked file does not exist
    as far as ownership, boundaries and the counted contract claims are concerned — and a
    local `verify` would then pass on a tree CI fails on.
    """
    run("git", "add", "--", *[str(p.relative_to(ROOT)) for p in paths], why="git add")


def actually_changed(paths: list[Path]) -> list[Path]:
    """Of the files handed to the snapshot writer, the ones it really rewrote.

    `./run surfaces --update` writes all five snapshots; a backend feature moves two of them
    and a frontend feature one. Reporting the other three as modified would be a small lie in
    the one place a reader is deciding what to review.
    """
    result = subprocess.run(
        ["git", "diff", "--cached", "--name-only"], cwd=ROOT, capture_output=True, text=True
    )
    changed = set(result.stdout.split())
    return [p for p in paths if str(p.relative_to(ROOT)) in changed]


def absorb_hub_growth(command: str) -> bool:
    """Raise the fan-in baseline for whatever the new unit legitimately depends on.

    A guarded route imports `get_current_user`, so every backend feature adds one dependent
    to the auth choke point; a view wraps itself in `AppShell`, so every frontend feature
    adds one there. `RULE-ARCH-003` is a ratchet and it fires on exactly that.

    Raising it here is not the rule being evaded. The rule forbids a hub growing SILENTLY,
    and this is the opposite of silent: the new number lands in the diff with the line below
    naming the command that moved it and the date it moved, for the same review as any
    hand-written raise. Allowlisting the file instead was the alternative and it is worse —
    it would remove the signal permanently, for every future dependent, including the ones
    that are not a new route at all.
    """
    result = subprocess.run(
        ["python3", "tools/index/boundaries.py"], cwd=ROOT, capture_output=True, text=True
    )
    if result.returncode != 0:
        raise Tooling(f"the boundary report could not run:\n{result.stderr}")
    regressions = json.loads(result.stdout)["hub_regressions"]
    if not regressions:
        return False

    text = BASELINE.read_text(encoding="utf-8")
    today = dt.date.today().isoformat()
    for regression in regressions:
        note = (
            f"# Raised from {regression['baseline']} on {today} by\n"
            f"# `{command}`: the generated unit is one more dependent\n"
            "# on a file that is depended on by design. A generator raising a ratchet is still a\n"
            "# ratchet being raised — it is in this diff, and it reviews like any other line.\n"
        )
        entry = f'"{regression["file"]}" = '
        pattern = re.compile("^" + re.escape(entry) + r"\d+$", re.MULTILINE)
        replacement = f"{note}{entry}{regression['fan_in']}"
        if pattern.search(text):
            text = pattern.sub(lambda _m: replacement, text, count=1)
        else:
            text = text.replace("[hubs]\n", f"[hubs]\n{replacement}\n", 1)
    BASELINE.write_text(text, encoding="utf-8")
    return True


def finish(created: list[Path], modified: list[Path], command: str) -> list[Path]:
    """Leave the repository in the state `./run verify` expects, in the order that works.

    fix first (ruff and eslint may rewrite what was just written), then the snapshots (which
    boot the application, so they need the router already mounted), then the index, because
    every step before it changed a tracked file — and then the fan-in baseline, which can
    only be measured once the index has seen the new imports.
    """
    paths = created + modified
    stage(paths)
    run("tools/fix.sh", why="make fix")
    run(
        "backend/.venv/bin/python",
        "tools/surfaces.py",
        "--update",
        why="./run surfaces --update",
    )
    paths += sorted((ROOT / "ops" / "surfaces").glob("*"))
    stage(paths)
    run("python3", "tools/index/build.py", why="./run index")

    if absorb_hub_growth(command):
        paths.append(BASELINE)
        stage(paths)
        run("python3", "tools/index/build.py", why="./run index")
    return actually_changed(paths)


