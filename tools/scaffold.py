# --- naming -------------------------------------------------------------------


def pascal(name: str) -> str:
    return "".join(part.capitalize() for part in name.split("_"))


def title(name: str) -> str:
    return name.replace("_", " ").capitalize()


def render(template: str, name: str) -> str:
    """Fill a template. Placeholders are `@NAME@`-shaped so that nothing in the generated
    Python, Vue or TOML has to be escaped to survive being a template."""
    return (
        template.replace("@PASCAL@", pascal(name))
        .replace("@TITLE_LOWER@", title(name).lower())
        .replace("@TITLE@", title(name))
        .replace("@NAME@", name)
    )


