def parse(argv: list[str]) -> tuple[str, str]:
    values = {"KIND": "", "NAME": ""}
    for arg in argv:
        key, _, value = arg.partition("=")
        if key in values:
            values[key] = value.strip()
        else:
            raise NeedsInput(f"unrecognised argument `{arg}` — expected KIND=<kind> NAME=<name>")

    if not values["KIND"]:
        raise NeedsInput("KIND is required — one of: " + ", ".join(KINDS))
    if values["KIND"] not in KINDS:
        raise NeedsInput(f"unknown KIND `{values['KIND']}` — one of: " + ", ".join(KINDS))
    if not values["NAME"]:
        raise NeedsInput("NAME is required — a lowercase word, e.g. NAME=reports")
    if not NAME_PATTERN.match(values["NAME"]):
        raise NeedsInput(
            f"NAME `{values['NAME']}` is not usable — it becomes a Python module, a URL "
            "segment, a unit id and a component name, so it must match "
            f"{NAME_PATTERN.pattern} (e.g. reports, weekly_review)"
        )
    return values["KIND"], values["NAME"]


def rel(path: Path) -> str:
    return str(path.relative_to(ROOT))


def unit_id(kind: str, name: str) -> str:
    return f"be/feature/{name}" if kind == "backend-feature" else f"fe/{name}"


def report(kind: str, name: str, created: list[Path], touched: list[Path]) -> None:
    made = [rel(p) for p in created]
    changed = sorted({rel(p) for p in touched} - set(made))
    if os.environ.get("RUNWAY_JSON") == "1":
        print(
            json.dumps(
                {
                    "command": "scaffold",
                    "status": "ok",
                    "kind": kind,
                    "name": name,
                    "unit": unit_id(kind, name),
                    "created": made,
                    "modified": changed,
                }
            )
        )
        return

    print(f"scaffolded {unit_id(kind, name)} ({kind})\n")
    print("  created")
    for path in made:
        print(f"    {path}")
    print("\n  modified")
    for path in changed:
        print(f"    {path}")
    print("\nEverything above is staged. Next:")
    print("  ./run verify          # green with no manual edits — that is the point")
    print("  ./run brief           # the brief needs your intent; the scaffold has none")
    print("\nRemoving it again: docs/task-interface.md#make-scaffold")


def main(argv: list[str]) -> int:
    try:
        kind, name = parse(argv)
        if not (ROOT / "backend" / ".venv" / "bin" / "python").exists():
            raise Tooling("backend/.venv is missing — run make bootstrap")
        created, modified = (backend_feature if kind == "backend-feature" else frontend_feature)(
            name
        )
        touched = finish(created, modified, f"./run scaffold KIND={kind} NAME={name}")
    except NeedsInput as e:
        print(f"scaffold: {e}", file=sys.stderr)
        print("\n  ./run scaffold KIND=backend-feature NAME=reports", file=sys.stderr)
        print("  ./run scaffold KIND=frontend-feature NAME=reports", file=sys.stderr)
        return EX_NEEDS_INPUT
    except Tooling as e:
        print(f"scaffold: {e}", file=sys.stderr)
        return EX_TOOLING
    report(kind, name, created, touched)
    return EX_OK


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
