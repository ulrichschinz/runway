"""Create a new unit that is conformant to every applicable rule by construction.

    ./run scaffold KIND=backend-feature  NAME=reports
    ./run scaffold KIND=frontend-feature NAME=reports

WHY THIS EXISTS. Every rule in the ledger has a fixture proving it able to fail, and there
are dozens of them. A person adding a backend feature by hand has to remember a unit registration
in `architecture.toml`, an allowed-edge list that does not accidentally grant the
Taskwarrior door, a guard declaration in `rules/route-guards.toml`, two test tiers, the
coverage floor, two public-surface snapshots, two counted claims in `AGENTS.md`, and a
`git add` early enough for the index to see the files at all. Every one of those is a place
to be right, and the failure mode of forgetting the guard declaration is the interesting
one: the route works, it just works for everybody.

So the first commit of a new unit is generated rather than remembered. What comes out is
not a template with TODOs in it — it is a working, guarded, tested, snapshotted slice that
`./run verify` passes with nothing edited by hand. Replacing what it returns is then a
normal change, with the gate already holding the shape.

WHAT IT DELIBERATELY DOES NOT DO. It does not design the feature, it does not write a
Change Impact Brief (that needs intent — `./run brief` pre-fills one), and it does not
commit. See docs/adr/0029-the-scaffold-generator.md.

Exit codes follow the interface contract: 0 ok, 2 needs input (a missing or unknown KIND or
NAME, or a unit that already exists), 3 tooling.
"""

