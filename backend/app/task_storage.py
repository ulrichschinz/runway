"""Which directory an account's Taskwarrior store lives in — decided here and nowhere else.

**Finding SEC-001.** Until brief 0065 the registered username was joined onto `DATA_ROOT` and
handed to the binary as `TASKDATA`, `TASKRC` and `HOME`. A username is caller-chosen text, so
`alice/../alice` opened alice's store and `../x` created directories above the data root. The
SEC-3 hardening in `task_runner` protects the *argument list*; this protects the *environment*,
which was the other half of the same tenancy boundary.

**The control** (ADR 0043, decision gate D1): every account carries a `storage_id` — 32 hex
characters from `secrets.token_hex`, generated by the server, unique, never rewritten — and
the store is `DATA_ROOT/<storage_id>/`. `resolve` is the only function that turns an account
into a path, it accepts only that shape, and it refuses anything that is not a real directory
directly under the resolved root. `RULE-SEC-003` holds the "only" in place: no other module may
build a path from `settings.data_root`.

**The transition.** Accounts created before the switch are `storage_layout='legacy'` and their
data is still in `DATA_ROOT/<username>/` until `app.services.storage_migration` has copied it.
In `compat` mode such an account is served from there — but only when the name is one path
component that is, in exactly that spelling, a real directory directly under the root, so an
alias like `alice/../alice`, or `ALICE` on a case-insensitive filesystem, is refused rather
than followed. In `strict` mode every legacy account is
refused. The `compat` branch is `SHIM-SEC-007` in `rules/shims.yaml`, with an expiry.

A leaf: it reads `settings` and the filesystem, opens no database and imports nothing above it,
so `be/di`, `be/services` and `be/adapters` can all reach it.
"""

from __future__ import annotations

import os
import re
import secrets
import stat
import unicodedata
from dataclasses import dataclass
from pathlib import Path

from app.config import settings

# What a storage id is. Lower-case hex only: no separator, no dot, no case-folding alias on a
# case-insensitive filesystem, and nothing that can equal `audit.db` or a staging name.
STORAGE_ID_RE = re.compile(r"[0-9a-f]{32}")

LAYOUT_LEGACY = "legacy"
LAYOUT_STORAGE_ID = "storage_id"
LAYOUTS = (LAYOUT_LEGACY, LAYOUT_STORAGE_ID)

MODE_COMPAT = "compat"
MODE_STRICT = "strict"
MODES = (MODE_COMPAT, MODE_STRICT)

TASKRC_NAME = ".taskrc"

# Entries in DATA_ROOT that are not an account's store and must never be served as one.
RESERVED_NAMES = frozenset({"audit.db", "audit.db-journal", "audit.db-wal", "audit.db-shm"})

USERNAME_MAX = 64


class StorageRefused(RuntimeError):
    """The account has no store this resolver is willing to hand to Taskwarrior.

    A RuntimeError, so every router already maps it to 500: the caller did nothing wrong, the
    server will not serve this account's data. `reason` is a short fixed phrase for the audit
    row and the log; it never contains a path.
    """

    def __init__(self, reason: str) -> None:
        super().__init__("Task storage is unavailable for this account")
        self.reason = reason


@dataclass(frozen=True)
class Account:
    """An account as the storage boundary sees it. Returned by `database.get_account`."""

    id: int
    username: str
    storage_id: str
    storage_layout: str


@dataclass(frozen=True)
class TaskStore:
    """One account's Taskwarrior directory, already resolved and checked.

    The only thing `task_runner._run` accepts. `account` is carried for logs and audit rows; it
    plays no part in which directory is opened.
    """

    path: Path
    account: str = ""

    @property
    def taskrc(self) -> Path:
        return self.path / TASKRC_NAME


def new_storage_id() -> str:
    """A fresh id. 128 bits from the OS CSPRNG, so a collision is not a design concern; the
    unique index on `users.storage_id` turns one into an error rather than a shared store."""
    return secrets.token_hex(16)


def is_storage_id(value: object) -> bool:
    return isinstance(value, str) and STORAGE_ID_RE.fullmatch(value) is not None


def storage_mode() -> str:
    """The configured mode. Anything unrecognised is `strict`: a typo must fail closed."""
    mode = (settings.task_storage_mode or "").strip().lower()
    return mode if mode in MODES else MODE_STRICT


def data_root() -> Path:
    """The resolved data root. Every path this module returns is a direct child of it."""
    return Path(settings.data_root).resolve()


def data_root_is_directory() -> bool:
    """Whether the data root exists and is a directory. Never creates it: the migration asks
    first, so an unmounted volume is an error rather than a fresh, empty root."""
    try:
        return stat.S_ISDIR(os.stat(data_root()).st_mode)
    except (OSError, ValueError):
        return False


def storage_dir(storage_id: str) -> Path:
    """`DATA_ROOT/<storage_id>`, for a well-formed id. Does not touch the filesystem."""
    if not is_storage_id(storage_id):
        raise StorageRefused("malformed storage id")
    return data_root() / storage_id


def staging_dir(storage_id: str) -> Path:
    """Where the migration assembles a copy before renaming it into place."""
    return storage_dir(storage_id).with_name(f".{storage_id}.partial")


def username_problem(username: str) -> str | None:
    """Why `username` is not acceptable for a NEW account, or None.

    Hygiene for a login and display attribute — explicitly **not** the path control. Path
    safety comes from `storage_id` alone and must never depend on this function again. The
    rule exists so a name cannot smuggle a terminal escape into an audit row or a log, cannot
    look like a path to a human reading either, and cannot have two canonically equal
    spellings that are different accounts.
    """
    if not username:
        return "username must not be empty"
    if len(username) > USERNAME_MAX:
        return f"username must be at most {USERNAME_MAX} characters"
    if username != username.strip():
        return "username must not start or end with whitespace"
    if unicodedata.normalize("NFC", username) != username:
        return "username must be in Unicode normalisation form NFC"
    if any(unicodedata.category(ch)[0] == "C" for ch in username):
        return "username must not contain control or format characters"
    if "/" in username or "\\" in username or username in (".", ".."):
        return "username must not look like a path"
    return None


# The names the migration gives its own directories in DATA_ROOT: `.<id>.partial` while a copy
# is assembled, `.<id>.rolled-back.<stamp>` for a copy a rollback set aside. Never a store.
TOOL_DIR_RE = re.compile(r"\.[0-9a-f]{32}\..*", re.DOTALL)


def _legacy_component_problem(username: str, *, allow_storage_id_shape: bool = False) -> str | None:
    """Why `DATA_ROOT/<username>` must not be served for a legacy account, or None.

    Syntactic only, and deliberately no narrower than "one path component that is no entry of
    this service's own": every name the previous image accepted and that is its own directory
    stays reachable, so a `.hidden` or a `back\\slash` account is not cut off by the deploy.
    Spellings a filesystem folds together (`ALICE` opening `alice` on APFS, NFD opening NFC)
    are not decided here — `checked_legacy_directory` requires the exact spelling on disk, and
    the migration groups accounts by inode.

    A 32-hex name is refused for serving (it could address another account's new store; the
    resolver has no database to tell). The migration passes `allow_storage_id_shape=True`
    because it compares the name against every account's storage id first.
    """
    if not username or username in (".", ".."):
        return "legacy name is a relative path"
    if "/" in username or "\x00" in username:
        return "legacy name contains a separator"
    if os.path.isabs(username) or Path(username).name != username:
        return "legacy name is not a single path component"
    if username in RESERVED_NAMES or TOOL_DIR_RE.fullmatch(username):
        return "legacy name collides with a reserved entry"
    if is_storage_id(username) and not allow_storage_id_shape:
        return "legacy name collides with a reserved entry"
    return None


def legacy_dir(username: str, *, allow_storage_id_shape: bool = False) -> Path:
    """`DATA_ROOT/<username>` for an existing legacy account, or `StorageRefused`.

    The checks are syntactic and do not touch the filesystem; `checked_legacy_directory`
    does that.
    """
    problem = _legacy_component_problem(username, allow_storage_id_shape=allow_storage_id_shape)
    if problem:
        raise StorageRefused(problem)
    return data_root() / username


def legacy_identity(username: str) -> tuple[int, int] | None:
    """`(st_dev, st_ino)` of what the pre-0065 code opened for this name — the name joined onto
    the data root verbatim and resolved by the OS, folding included. For the migration's alias
    detection only: compared, never served; None when nothing exists there.

    Identity, not spelling: on a case- or normalisation-insensitive filesystem `Alice` and
    `alice` are two different strings and one directory, and a directory cannot be hard-linked,
    so one inode is one store.
    """
    try:
        info = os.stat(os.path.join(data_root(), username))
    except (OSError, ValueError):
        return None
    return (info.st_dev, info.st_ino)


def store_identity(storage_id: str) -> tuple[int, int] | None:
    """`(st_dev, st_ino)` of `DATA_ROOT/<storage_id>`, or None. For alias detection only."""
    if not is_storage_id(storage_id):
        return None
    try:
        info = os.stat(storage_dir(storage_id))
    except OSError:
        return None
    return (info.st_dev, info.st_ino)


def set_aside_dir(storage_id: str, stamp: str) -> Path:
    """Where a rollback moves the copy it no longer serves, so a later `apply` can copy fresh."""
    return storage_dir(storage_id).with_name(f".{storage_id}.rolled-back.{stamp}")


def spelled_on_disk(path: Path) -> bool:
    """Whether `path.name` is, byte for byte, an entry of its parent directory.

    `lstat("ALICE")` succeeds on a case-insensitive filesystem when only `alice` exists, and
    `realpath` keeps the spelling it was given, so neither notices the fold. The listing does:
    a case- and normalisation-preserving filesystem (APFS, ext4) lists the name a directory
    was created under.
    """
    try:
        with os.scandir(path.parent) as entries:
            return any(entry.name == path.name for entry in entries)
    except OSError:
        return False


def checked_directory(path: Path) -> Path:
    """`path`, if it is a real directory directly under the resolved data root.

    `lstat`, not `stat`: a symlink is refused even when it points somewhere harmless, because
    "harmless" is a property of the target at the moment of checking, not of the link.
    """
    root = data_root()
    if path.parent != root:
        raise StorageRefused("store is not a direct child of the data root")
    try:
        info = path.lstat()
    except FileNotFoundError:
        raise StorageRefused("store does not exist") from None
    if stat.S_ISLNK(info.st_mode):
        raise StorageRefused("store is a symlink")
    if not stat.S_ISDIR(info.st_mode):
        raise StorageRefused("store is not a directory")
    if path.resolve() != path:
        raise StorageRefused("store resolves outside the data root")
    return path


def checked_legacy_directory(path: Path) -> Path:
    """`checked_directory`, and the name must be the exact spelling of a directory on disk."""
    checked_directory(path)
    if not spelled_on_disk(path):
        raise StorageRefused("store is spelled differently on disk")
    return path


def resolve(account: Account, mode: str | None = None) -> TaskStore:
    """The one place an account becomes a directory. Raises `StorageRefused`."""
    mode = mode or storage_mode()
    if account.storage_layout == LAYOUT_STORAGE_ID:
        return TaskStore(checked_directory(storage_dir(account.storage_id)), account.username)
    if account.storage_layout != LAYOUT_LEGACY:
        raise StorageRefused("unknown storage layout")
    if mode != MODE_COMPAT:
        raise StorageRefused("legacy layout refused in strict mode")
    # SHIM-SEC-007: the pre-migration layout, served only for a safe single component.
    return TaskStore(checked_legacy_directory(legacy_dir(account.username)), account.username)
